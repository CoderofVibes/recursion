MU = 398600.4415e9  # GMAT Earth's documented point-mass default, m^3/s^2
G0 = 9.80665
DT = 10
BURN_S = 120
MASS_FLOW = 1000 / (320 * G0)  # kg/s for the C4 engine
R0 = (MU * (6000 / math.tau) ** 2) ** (1 / 3)
V0 = math.sqrt(MU / R0)
EPOCH_A1MJD = 21545
