"""Run S5 reference assertions and write deterministic JSON next to this script.

From the repository root: python -B tools/studies/s5/generate.py
Verify committed output without writing: add --check.
"""

import argparse
import json
from pathlib import Path

from lattice_reference import build_vectors as lattice_vectors
from wells_reference import build_vectors as well_vectors


def main():
    if not __debug__:
        raise SystemExit("Assertions are the reference checks; do not use python -O.")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare regenerated bytes without writing")
    args = parser.parse_args()
    result = {
        "schema": "recursion.s5.reference.v1",
        "status": "Proposed fictional fields; numerical reference, not game implementation or playtest",
        "reproduce": "python -B tools/studies/s5/generate.py",
        "dependencies": "Python 3.14 standard library and numpy; no downloaded data or random draws",
        "well": well_vectors(),
        "lattice": lattice_vectors(),
    }
    data = (json.dumps(result, sort_keys=True, indent=2, allow_nan=False) + "\n").encode("utf-8")
    destination = Path(__file__).with_name("vectors.json")
    if args.check:
        if not destination.exists() or destination.read_bytes() != data:
            raise SystemExit("FAIL: vectors.json differs from regenerated output")
        verb = "Verified"
    else:
        destination.write_bytes(data)
        verb = "Wrote"
    print(f"{verb} {destination.name}; well assertions and {len(result['lattice']['checks'])} lattice checks passed.")


if __name__ == "__main__":
    main()
